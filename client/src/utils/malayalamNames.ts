// Pre-sorted list of keys by length descending to ensure longer phrases match before generic single words
const SORTED_KEYS = Object.keys(MALAYALAM_PRODUCT_NAMES).sort((a, b) => b.length - a.length);

const MODIFIER_WORDS = [
  'sauce',
  'ketchup',
  'paste',
  'puree',
  'pickle',
  'chips',
  'squash',
  'truffles',
  'cookies',
  'biscuit',
  'powder',
  'masala',
  'oil',
  'syrup',
  'jam',
  'spread',
  'noodles',
];

export function getMalayalamName(name: string): string {
  if (!name) return '';
  const trimmed = name.trim();
  // Check if it's already in Malayalam script (Unicode range for Malayalam: 0D00–0D7F)
  if (/[\u0D00-\u0D7F]/.test(trimmed)) {
    return trimmed;
  }

  const lower = trimmed.toLowerCase();

  // 1. Direct exact dictionary match
  if (MALAYALAM_PRODUCT_NAMES[lower]) {
    return MALAYALAM_PRODUCT_NAMES[lower];
  }

  // 2. Check compound phrases first (e.g. 'tomato sauce' matches before 'tomato')
  for (const key of SORTED_KEYS) {
    if (lower.includes(key)) {
      // Safety check: if key is a raw single produce (like 'tomato' or 'banana')
      // but the product title contains a modifier word (like 'sauce', 'chips', 'pickle', 'powder'),
      // do NOT misclassify it as raw vegetable/fruit!
      const isRawSingleProduce = ['tomato', 'banana', 'chilli', 'onion', 'mango', 'orange', 'grape', 'strawberry', 'coconut', 'garlic', 'ginger'].includes(key);
      if (isRawSingleProduce) {
        const hasModifier = MODIFIER_WORDS.some((mod) => lower.includes(mod));
        if (hasModifier) {
          // Skip raw single produce match so it matches compound phrase or keeps its title!
          continue;
        }
      }
      return MALAYALAM_PRODUCT_NAMES[key];
    }
  }

  return trimmed;
}
